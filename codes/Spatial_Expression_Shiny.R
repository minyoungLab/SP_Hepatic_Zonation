token_match <- function(x, target){
  
  x <- as.character(x)
  
  x[
    is.na(x)
  ] <- ""
  
  
  target <- toupper(
    trimws(
      target
    )
  )
  
  
  x <- toupper(
    x
  )
  
  
  vapply(
    
    strsplit(
      x,
      "[;,|]"
    ),
    
    function(z){
      
      any(
        trimws(z) == target
      )
      
    },
    
    logical(1)
    
  )
}


