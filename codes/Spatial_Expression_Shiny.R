clean_run_name <- function(x){
  
  x <- as.character(x)
  
  x <- str_replace_all(
    x,
    "\\\\",
    "/"
  )
  
  x <- basename(x)
  
  x <- tools::file_path_sans_ext(x)
  
  x
}


############################################################
# 7. Set-name normalization
############################################################

normalize_set_name <- function(x){
  
  toupper(
    gsub(
      "[^A-Za-z0-9]",
      "",
      x
    )
  )
  
}


############################################################
# 8. Set detection
############################################################

detect_set <- function(run_name){
  
  run_normalized <- normalize_set_name(
    run_name
  )
  
  
  result <- rep(
    NA_character_,
    length(run_name)
  )
  
  
  for(sn in set_names){
    
    sn_normalized <- normalize_set_name(
      sn
    )
    
    
    idx <- is.na(result) &
      str_detect(
        run_normalized,
        fixed(
          sn_normalized
        )
      )
    
    
    result[idx] <- sn
  }
  
  
  result
}


############################################################
# 9. ROI number extraction
############################################################

get_ROI_number <- function(x){
  
  
  ##########################################################
  # Priority 1
  #
  # ROI1
  # ROI01
  # ROI001
  # ROI_1
  # ROI-1
  ##########################################################
  
  roi_match <- str_match(
    
    x,
    
    regex(
      "ROI[_\\- ]*0*([0-9]{1,3})",
      ignore_case = TRUE
    )
    
  )[,2]
  
  
  ##########################################################
  # Priority 2
  #
  # 마지막 숫자
  #
  # GF1-2_025
  ##########################################################
  
  trailing_match <- str_match(
    
    x,
    
    "0*([0-9]{1,3})$"
    
  )[,2]
  
  
  result <- ifelse(
    
    !is.na(roi_match),
    
    roi_match,
    
    trailing_match
    
  )
  
  
  suppressWarnings(
    as.integer(
      result
    )
  )
}


